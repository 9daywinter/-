def main():
    bad = 0
    for text, want_title, want_s, want_e in CASES:
        r = resolve_event_time(text, NOW)
        got_s, got_e = r["start_at"].strftime("%Y-%m-%d %H:%M"), r["end_at"].strftime("%Y-%m-%d %H:%M")
        ok = (got_s == want_s and got_e == want_e and r["title"] == want_title)
        mark = "PASS" if ok else "FAIL"
        if not ok:
            bad += 1
            print(f"{mark}  {text}")
            print(f"      期望: {want_title!r} {want_s} → {want_e}")
            print(f"      实际: {r['title']!r} {got_s} → {got_e}")
        else:
            print(f"{mark}  {text} → {r['title']}  {got_s[5:]} → {got_e[5:]}")
    print(f"\n{len(CASES) - bad}/{len(CASES)} 通过")
    return bad


if __name__ == "__main__":
    raise SystemExit(main())
